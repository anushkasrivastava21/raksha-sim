R_PEAK_OFFSET = 99          # samples before the R-peak in every training window


def beat_windows(raw, fs: float = FS_HZ) -> list:
    """Split an ECG strip into R-peak-aligned WINDOW-sample raw windows.

    A strip no longer than ~1.2 windows is assumed to be one pre-aligned beat
    (what the ESP32 sends if it does its own R detection). Longer strips are
    band-passed, peaks found on |signal| (polarity-agnostic), and each beat is
    cut exactly like the training data: [R - 99, R + 157).
    """
    from scipy.signal import find_peaks, sosfiltfilt
    x = np.asarray(raw, dtype=np.float64)
    if abs(fs - FS_HZ) > 1e-6:
        n = int(round(x.size * FS_HZ / fs))
        x = np.interp(np.linspace(0, 1, n), np.linspace(0, 1, x.size), x)
    if x.size <= int(1.2 * WINDOW):
        return [x]
    sos, _ = coefficients()
    env = np.abs(sosfiltfilt(sos, x - x.mean()))
    peaks, _ = find_peaks(env, height=0.45 * np.percentile(env, 99.5),
                          distance=int(0.25 * FS_HZ))
    return [x[p - R_PEAK_OFFSET:p - R_PEAK_OFFSET + WINDOW] for p in peaks
            if p - R_PEAK_OFFSET >= 0 and p - R_PEAK_OFFSET + WINDOW <= x.size]
