"""ECG preprocessing shared by training, the Python runtime and the Dart port.

Training and on-device inference MUST apply byte-for-byte the same transform,
otherwise a model that scores well offline silently degrades on the phone.
So the filter is implemented here explicitly (Direct-Form-II-transposed
biquads + scipy's odd-extension filtfilt) instead of calling scipy at runtime.
scipy is only used once, to design the coefficients, which are then exported
as constants for lib/ml/ecg_preprocess.dart.

Pipeline: resample to WINDOW -> zero-phase bandpass -> zero-mean -> peak-normalise
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np

FS_HZ = 360.0          # MIT-BIH rate; the ESP32 must send this or be resampled to it
WINDOW = 256           # samples fed to the CNN (~0.71 s at 360 Hz)
BAND = (0.5, 45.0)
ORDER = 4


@lru_cache(maxsize=1)
def coefficients() -> tuple[np.ndarray, np.ndarray]:
    """(sos [n,6], zi [n,2]) - designed once with scipy."""
    from scipy.signal import butter, sosfilt_zi
    high = min(BAND[1], FS_HZ / 2 * 0.99)
    sos = butter(ORDER, [BAND[0], high], btype="bandpass", fs=FS_HZ, output="sos")
    return sos, sosfilt_zi(sos)


def _sosfilt(sos: np.ndarray, x: np.ndarray, zi: np.ndarray) -> np.ndarray:
    y = x.astype(np.float64).copy()
    z = zi.astype(np.float64).copy()
    for s in range(sos.shape[0]):
        b0, b1, b2, _, a1, a2 = sos[s]
        z0, z1 = z[s]
        for i in range(y.size):
            xi = y[i]
            yi = b0 * xi + z0
            z0 = b1 * xi - a1 * yi + z1
            z1 = b2 * xi - a2 * yi
            y[i] = yi
    return y


def filtfilt(x: np.ndarray) -> np.ndarray:
    """Equivalent to scipy.signal.sosfiltfilt(sos, x, padlen=min(3*(2n+1), len-1))."""
    sos, zi = coefficients()
    x = np.asarray(x, dtype=np.float64)
    pad = min(3 * (2 * sos.shape[0] + 1), x.size - 1)
    if pad < 1:
        return x - x.mean()
    ext = np.concatenate((2 * x[0] - x[pad:0:-1], x, 2 * x[-1] - x[-2:-pad - 2:-1]))
    y = _sosfilt(sos, ext, zi * ext[0])
    y = _sosfilt(sos, y[::-1], zi * y[-1])[::-1]
    return y[pad:-pad]


def preprocess(raw) -> np.ndarray:
    """Raw ADC window (any length >= 10) -> float32 (1, 1, WINDOW) model input."""
    x = np.asarray(raw, dtype=np.float64)
    if x.size < 10:
        raise ValueError("ECG window too short")
    if x.size != WINDOW:
        x = np.interp(np.linspace(0, 1, WINDOW), np.linspace(0, 1, x.size), x)
    y = filtfilt(x)
    y -= y.mean()
    peak = np.abs(y).max()
    if peak > 0:
        y /= peak
    return y.astype(np.float32).reshape(1, 1, WINDOW)


def export_constants(path: Path) -> None:
    sos, zi = coefficients()
    path.write_text(json.dumps({"fs_hz": FS_HZ, "window": WINDOW, "band": BAND,
                                "order": ORDER, "sos": sos.tolist(), "zi": zi.tolist()}))


def preprocess_batch(windows: np.ndarray) -> np.ndarray:
    """Vectorised version for training (N, WINDOW) -> (N, 1, WINDOW).

    Uses scipy.sosfiltfilt, which is proven identical to filtfilt() above by
    tests/test_ecg_preprocess.py; the loop version is too slow for 100k beats.
    """
    from scipy.signal import sosfiltfilt
    sos, _ = coefficients()
    w = np.asarray(windows, dtype=np.float64)
    if w.shape[1] != WINDOW:
        raise ValueError(f"expected windows of {WINDOW}")
    pad = min(3 * (2 * sos.shape[0] + 1), WINDOW - 1)
    y = sosfiltfilt(sos, w, axis=-1, padlen=pad)
    y -= y.mean(axis=1, keepdims=True)
    peak = np.abs(y).max(axis=1, keepdims=True)
    y = np.divide(y, peak, out=y, where=peak > 0)
    return y.astype(np.float32)[:, None, :]


